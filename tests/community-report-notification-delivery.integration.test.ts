import { createHash, randomUUID } from "node:crypto";
import { and, eq, inArray, sql } from "drizzle-orm";
import { afterEach, expect, it, vi } from "vitest";
import {
  communityReportsRepository as repository,
  db,
  discussionRevision,
  notificationRepository,
  sessionRepository,
  userRepository,
  webPushSubscriptionRepository,
} from "@nexus/db";
import {
  auditEvents,
  comments,
  content,
  notifications,
  reports,
  users,
  webPushOutbox,
} from "../packages/db/src/schema";

const actors: string[] = [];
const triggers: { table: string; name: string }[] = [];
const id = (prefix: string) => `${prefix}_report_notice_${randomUUID().replaceAll("-", "")}`;
const noticeId = (auditId: string, reporterId: string) =>
  `ntf_report_${createHash("sha256")
    .update(JSON.stringify([auditId, reporterId]))
    .digest("hex")}`;

afterEach(async () => {
  vi.restoreAllMocks();
  for (const { table, name } of triggers.splice(0)) {
    await db.execute(sql.raw(`drop trigger if exists ${name} on ${table}`));
    await db.execute(sql.raw(`drop function if exists ${name}()`));
  }
  if (actors.length) {
    await db.delete(auditEvents).where(inArray(auditEvents.actorId, actors));
    await db.delete(users).where(inArray(users.id, actors));
  }
  actors.length = 0;
});

async function actor(role = "user") {
  const userId = id("usr");
  const row = await userRepository.create({
    id: userId,
    username: userId,
    email: `${userId}@nexus.test`,
    displayName: "Report notice fixture",
    role,
  });
  actors.push(row.id);
  return row;
}

async function fixture() {
  const author = await actor();
  const reporter = await actor();
  const moderator = await actor("moderator");
  const [publication] = await db
    .insert(content)
    .values({
      id: id("cnt"),
      slug: id("post"),
      title: "Private target title",
      body: "Private target body",
      authorId: author.id,
      commentCount: 1,
    })
    .returning();
  const [comment] = await db
    .insert(comments)
    .values({
      id: id("cmt"),
      contentId: publication.id,
      authorId: author.id,
      text: "Private target text",
    })
    .returning();
  return { author, reporter, moderator, publication, comment };
}

async function submit(
  f: Awaited<ReturnType<typeof fixture>>,
  targetType: "comment" | "content" = "comment",
  reporterId = f.reporter.id,
) {
  return repository.submit({
    id: id("rpt"),
    auditId: id("aud"),
    actorId: reporterId,
    targetType,
    targetId: targetType === "comment" ? f.comment.id : f.publication.id,
    type: "abuse",
    reason: "Private complaint reason",
    evidenceUrls: [],
  });
}

async function device(userId: string) {
  const sessionId = id("ses");
  await sessionRepository.create({
    id: sessionId,
    userId,
    token: id("token"),
    expiresAt: new Date(Date.now() + 60 * 60 * 1000),
  });
  const subscriptionId = id("wps");
  await webPushSubscriptionRepository.upsert({
    id: subscriptionId,
    userId,
    sessionId,
    endpoint: `https://push.example.invalid/${subscriptionId}`,
    p256dh: "fixture-key",
    auth: "fixture-auth",
    expirationAt: null,
  });
}

async function failInsert(
  table: "notifications" | "web_push_outbox",
  column: "recipient_id" | "notification_id",
  value: string,
) {
  // Every interpolated identifier/value is generated by this fixture, never user input.
  const name = `report_notice_failure_${randomUUID().replaceAll("-", "")}`;
  if (!/^[A-Za-z0-9_]+$/u.test(value)) throw Error("Unsafe fixture ID");
  await db.execute(
    sql.raw(
      `create function ${name}() returns trigger language plpgsql as $$ begin raise exception 'PRIVATE_INSERT_FAILURE'; end $$`,
    ),
  );
  triggers.push({ table, name });
  await db.execute(
    sql.raw(
      `create trigger ${name} before insert on ${table} for each row when (new.${column} = '${value}') execute function ${name}()`,
    ),
  );
  return async () => {
    await db.execute(sql.raw(`drop trigger ${name} on ${table}`));
    await db.execute(sql.raw(`drop function ${name}()`));
    triggers.splice(
      triggers.findIndex((trigger) => trigger.name === name),
      1,
    );
  };
}

function decision(f: Awaited<ReturnType<typeof fixture>>, reportId: string) {
  return {
    id: reportId,
    actorId: f.moderator.id,
    expectedStatus: "open" as const,
    action: "review" as const,
    notes: "Private moderator notes",
    auditId: id("aud"),
    removalAuditId: id("aud"),
  };
}

it("commits a private security outcome and push job with the decision, preserving read state on retry", async () => {
  const f = await fixture();
  const report = await submit(f);
  await device(f.reporter.id);
  await notificationRepository.updatePreferences(f.reporter.id, {
    followsEnabled: false,
    contentEnabled: false,
    commerceEnabled: false,
    serverEnabled: false,
    systemEnabled: false,
  });
  const command = decision(f, report.id);
  await repository.decide(command);
  const expectedId = noticeId(command.auditId, f.reporter.id);
  const [notice] = await db.select().from(notifications).where(eq(notifications.id, expectedId));
  expect(notice).toMatchObject({
    recipientId: f.reporter.id,
    title: "Community report status",
    message: "Report status: under_review.",
    link: `/workspace/reports/${report.id}`,
    category: "security",
    type: "security",
  });
  expect(JSON.stringify(notice)).not.toMatch(/Private target|Private complaint|Private moderator/u);
  expect(
    await db.select().from(webPushOutbox).where(eq(webPushOutbox.notificationId, expectedId)),
  ).toHaveLength(1);
  await db.update(notifications).set({ isRead: true }).where(eq(notifications.id, expectedId));
  await expect(repository.decide(command)).rejects.toMatchObject({ code: "REPORT_STATE_CHANGED" });
  const duplicate = await db.transaction((tx) =>
    notificationRepository.createWithPushOutboxWithin(
      tx,
      {
        id: expectedId,
        recipientId: f.reporter.id,
        title: notice.title,
        message: notice.message,
        link: `/workspace/reports/${report.id}`,
        type: "security",
        category: "security",
      },
      true,
    ),
  );
  expect(duplicate).toMatchObject({ notification: null, pushJobs: 0 });
  const [retained] = await db.select().from(notifications).where(eq(notifications.id, expectedId));
  expect(retained.isRead).toBe(true);
  expect(retained.createdAt).toEqual(notice.createdAt);
  expect(
    await db.select().from(webPushOutbox).where(eq(webPushOutbox.notificationId, expectedId)),
  ).toHaveLength(1);
});

it("rolls back comment removal, both audits and the author notice when reporter inbox insertion fails", async () => {
  const f = await fixture();
  const report = await submit(f);
  await failInsert("notifications", "recipient_id", f.reporter.id);
  const command = {
    ...decision(f, report.id),
    action: "remove_comment" as const,
    expectedRevision: discussionRevision(f.comment.id, f.comment.text),
  };
  await expect(repository.decide(command)).rejects.toThrow();
  expect(await db.select().from(comments).where(eq(comments.id, f.comment.id))).toHaveLength(1);
  const [publication] = await db.select().from(content).where(eq(content.id, f.publication.id));
  expect(publication.commentCount).toBe(1);
  const [stored] = await db.select().from(reports).where(eq(reports.id, report.id));
  expect(stored.status).toBe("open");
  expect(
    await db
      .select()
      .from(auditEvents)
      .where(inArray(auditEvents.id, [command.auditId, command.removalAuditId])),
  ).toHaveLength(0);
  expect(
    await db
      .select()
      .from(notifications)
      .where(inArray(notifications.recipientId, [f.author.id, f.reporter.id])),
  ).toHaveLength(0);
});

it.each(["comment", "content"] as const)(
  "rolls back the entire %s batch if any reporter inbox insert fails, then permits a safe retry",
  async (targetType) => {
    const f = await fixture();
    const second = await actor();
    const firstReport = await submit(f, targetType);
    const secondReport = await submit(f, targetType, second.id);
    const input = {
      items: [firstReport, secondReport].map((report) => ({
        id: report.id,
        expectedStatus: "open" as const,
      })),
      action: "resolve" as const,
      notes: "Private batch notes",
    };
    const preview =
      targetType === "comment"
        ? await repository.previewDiscussionBatch(
            f.moderator.id,
            f.publication.id,
            f.comment.id,
            input,
          )
        : await repository.previewPublicationBatch(f.moderator.id, f.publication.id, input);
    const command = { ...input, previewRevision: preview.previewRevision };
    const auditIds = [id("aud"), id("aud")];
    const decide = () =>
      targetType === "comment"
        ? repository.decideDiscussionBatch(
            f.moderator.id,
            f.publication.id,
            f.comment.id,
            command,
            auditIds,
          )
        : repository.decidePublicationBatch(f.moderator.id, f.publication.id, command, auditIds);
    const removeFailure = await failInsert("notifications", "recipient_id", second.id);
    await expect(decide()).rejects.toThrow();
    const reportIds = [firstReport.id, secondReport.id];
    expect(
      (await db.select().from(reports).where(inArray(reports.id, reportIds))).map(
        (row) => row.status,
      ),
    ).toEqual(["open", "open"]);
    expect(
      await db.select().from(auditEvents).where(inArray(auditEvents.id, auditIds)),
    ).toHaveLength(0);
    expect(
      await db
        .select()
        .from(notifications)
        .where(inArray(notifications.recipientId, [f.reporter.id, second.id])),
    ).toHaveLength(0);
    await removeFailure();
    await decide();
    expect(
      await db.select().from(auditEvents).where(inArray(auditEvents.id, auditIds)),
    ).toHaveLength(2);
    const notices = await db
      .select()
      .from(notifications)
      .where(inArray(notifications.recipientId, [f.reporter.id, second.id]));
    expect(notices).toHaveLength(2);
    expect(notices.every((notice) => notice.message === "Report status: resolved.")).toBe(true);
    expect(JSON.stringify(notices)).not.toContain("Private batch notes");
  },
);

it("commits report, audit and inbox despite a queue-local database failure", async () => {
  const f = await fixture();
  const report = await submit(f);
  await device(f.reporter.id);
  const command = decision(f, report.id);
  const expectedId = noticeId(command.auditId, f.reporter.id);
  await failInsert("web_push_outbox", "notification_id", expectedId);
  const warning = vi.spyOn(console, "warn").mockImplementation(() => {});
  await repository.decide(command);
  expect(
    await db.select().from(notifications).where(eq(notifications.id, expectedId)),
  ).toHaveLength(1);
  expect(
    await db.select().from(auditEvents).where(eq(auditEvents.id, command.auditId)),
  ).toHaveLength(1);
  const [stored] = await db
    .select()
    .from(reports)
    .where(and(eq(reports.id, report.id), eq(reports.reporterId, f.reporter.id)));
  expect(stored.status).toBe("under_review");
  expect(
    await db.select().from(webPushOutbox).where(eq(webPushOutbox.notificationId, expectedId)),
  ).toHaveLength(0);
  expect(warning).toHaveBeenCalledWith(
    JSON.stringify({
      event: "notification.push_outbox_degraded",
      producer: "community_report",
      reason: "error",
    }),
  );
  expect(JSON.stringify(warning.mock.calls)).not.toContain("PRIVATE_INSERT_FAILURE");
});
