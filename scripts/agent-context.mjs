import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { classifyChanges, requiredJobs } from "./ci-policy.mjs";

const handbook = "docs/handbook";
export const queuePath = `${handbook}/59-DEVELOPMENT-QUEUE.md`;
export const contextLimits = {
  "AGENTS.md": 5500,
  [queuePath]: 7000,
  [`${handbook}/15-AI-CONTEXT-INDEX.md`]: 6000,
  [`${handbook}/60-AGENT-WORKFLOW.md`]: 12000,
};
const manifestPath = `${handbook}/MANIFEST-SHA256.md`;
const read = (root, path) => readFileSync(resolve(root, path), "utf8");
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");

export function parseTasks(source) {
  return source
    .split("\n")
    .filter((line) => /^\| [A-Z]+-\d+ \|/u.test(line))
    .map((line) => {
      const [id, state, owner, dependencies, outcome] = line
        .split("|")
        .slice(1, -1)
        .map((s) => s.trim());
      return {
        id,
        state,
        owner,
        dependencies: dependencies === "—" ? [] : dependencies.split(/,\s*/u),
        outcome,
      };
    });
}

function handbookFiles(root) {
  return readdirSync(resolve(root, handbook))
    .filter((name) => name.endsWith(".md") && name !== "MANIFEST-SHA256.md")
    .sort();
}

export function refreshManifest(root) {
  const files = handbookFiles(root);
  const rows = files.map((name) => {
    const bytes = readFileSync(resolve(root, handbook, name));
    return `| \`${name}\` | \`${digest(bytes)}\` | ${bytes.length} |`;
  });
  writeFileSync(
    resolve(root, manifestPath),
    [
      "# MTA NEXUS Handbook — SHA-256 Manifest",
      "",
      `Files hashed: **${files.length}**`,
      "",
      "Generated by `node scripts/agent-context.mjs --refresh-manifest`.",
      "Inventory of current handbook files, excluding this manifest. Content hashes detect drift;",
      "they are not signatures, product approval or evidence that the text is correct.",
      "",
      "| File | SHA-256 | Bytes |",
      "|---|---|---:|",
      ...rows,
      "",
    ].join("\n"),
  );
}

export function checkContext(root) {
  const errors = [];
  for (const [path, limit] of Object.entries(contextLimits)) {
    let source;
    try {
      source = read(root, path);
    } catch {
      errors.push(`Missing context file: ${path}`);
      continue;
    }
    const size = Buffer.byteLength(source);
    if (size > limit)
      errors.push(
        `${path}: ${size} bytes exceeds ${limit}; move detail to the relevant domain document`,
      );
    // Check relative file destinations in the short entry docs, not anchors or web URLs.
    for (const match of source.matchAll(/\[[^\]]+\]\(([^\s)]+)\)/gu)) {
      const target = match[1].split("#")[0];
      if (!target || /^(?:[a-z][a-z\d+.-]*:|\/)/iu.test(target)) continue;
      if (!existsSync(resolve(root, dirname(path), target)))
        errors.push(`${path}: missing link target ${target}`);
    }
  }
  let tasks = [];
  try {
    tasks = parseTasks(read(root, queuePath));
  } catch {
    /* Missing file already reported. */
  }
  if (!tasks.length) errors.push("Queue contains no task rows");
  const ids = new Set(tasks.map((task) => task.id));
  if (ids.size !== tasks.length) errors.push("Duplicate task ID in queue");
  const states = new Set(["ready", "active", "review", "blocked", "done"]);
  if (tasks.filter((task) => ["active", "review"].includes(task.state)).length > 1)
    errors.push("Only one implementation/review slice may be in flight");
  for (const task of tasks) {
    if (!states.has(task.state)) errors.push(`${task.id}: invalid state ${task.state}`);
    if (!task.owner || !task.outcome) errors.push(`${task.id}: owner and outcome are required`);
    if (["active", "review"].includes(task.state) && task.owner === "unassigned")
      errors.push(`${task.id}: active/review task needs an owner`);
    for (const dep of task.dependencies) {
      if (!ids.has(dep) || dep === task.id) errors.push(`${task.id}: invalid dependency ${dep}`);
    }
  }
  const visit = (id, path = new Set()) => {
    if (path.has(id)) return true;
    const next = new Set([...path, id]);
    return (
      tasks
        .find((task) => task.id === id)
        ?.dependencies.some((dep) => ids.has(dep) && visit(dep, next)) ?? false
    );
  };
  if (tasks.some((task) => visit(task.id))) errors.push("Cyclic task dependencies");
  try {
    const files = handbookFiles(root);
    const manifest = read(root, manifestPath);
    const rows = [...manifest.matchAll(/\| `([^`]+)` \| `([a-f\d]{64})` \| (\d+) \|/gu)];
    const listed = rows.map((row) => row[1]).sort();
    if (JSON.stringify(listed) !== JSON.stringify(files))
      errors.push("Handbook manifest inventory differs from files");
    if (!manifest.includes(`Files hashed: **${files.length}**`))
      errors.push("Handbook manifest count differs from files");
    for (const [, name, expected, size] of rows) {
      if (!files.includes(name)) continue;
      const bytes = readFileSync(resolve(root, handbook, name));
      if (digest(bytes) !== expected || bytes.length !== Number(size))
        errors.push(`Handbook manifest drift: ${name}`);
    }
  } catch (error) {
    errors.push(`Cannot check handbook manifest: ${error.message}`);
  }
  return errors;
}

export function nextTask(tasks) {
  return (
    tasks.find((task) => ["active", "review"].includes(task.state)) ??
    tasks.find(
      (task) =>
        task.state === "ready" &&
        task.dependencies.every((dep) => tasks.find((t) => t.id === dep)?.state === "done"),
    )
  );
}

export function brief(root) {
  const git = (args) => execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
  const files = [
    ...new Set(
      [
        ...git(["diff", "--name-only", "-z", "HEAD"]).split("\0"),
        ...git(["ls-files", "--others", "--exclude-standard", "-z"]).split("\0"),
      ].filter(Boolean),
    ),
  ].sort();
  const tasks = parseTasks(read(root, queuePath));
  const selected = nextTask(tasks);
  const pkg = JSON.parse(read(root, "package.json"));
  const policy = classifyChanges(files);
  const errors = checkContext(root);
  return [
    `MTA NEXUS | HEAD ${git(["rev-parse", "--short", "HEAD"])} | branch ${git(["branch", "--show-current"]) || "detached"}`,
    `Pins: Node ${read(root, ".nvmrc").trim()}, ${pkg.packageManager}; running ${process.version}`,
    `Local changes: ${files.length}${
      files.length
        ? `\n${files
            .slice(0, 20)
            .map((f) => `  ${JSON.stringify(f)}`)
            .join("\n")}`
        : " (clean)"
    }`,
    ...(files.length > 20 ? [`  ${files.length - 20} more; inspect git status --short`] : []),
    `Task: ${selected ? `${selected.id} (${selected.state}, ${selected.owner}): ${selected.outcome}` : "none eligible; inspect blockers/dependencies"}`,
    `Read: AGENTS.md, selected section of ${queuePath}, relevant section of ${handbook}/15-AI-CONTEXT-INDEX.md`,
    `Advisory CI for LOCAL uncommitted paths: ${requiredJobs(policy).join(", ")}`,
    "This is not the full PR/release diff. Required checks still follow ci-policy.mjs.",
    `Context integrity: ${errors.length ? `${errors.length} issue(s); run pnpm agent:check` : "pass (budgets, task graph, file links, manifest)"}`,
    "Production/remote publication is not authorized. This brief does not start agents or services.",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const args = process.argv.slice(2);
  try {
    if (!args.length) console.log(brief(root));
    else if (args.length === 1 && args[0] === "--check") {
      const errors = checkContext(root);
      if (errors.length) {
        console.error(errors.join("\n"));
        process.exitCode = 1;
      } else
        console.log(
          "Agent context: budgets, task graph, relative file links and handbook manifest passed (anchors not checked).",
        );
    } else if (args.length === 1 && args[0] === "--refresh-manifest") {
      refreshManifest(root);
      console.log("Refreshed handbook manifest; inspect the diff and run pnpm agent:check.");
    } else throw new Error("Usage: node scripts/agent-context.mjs [--check|--refresh-manifest]");
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
