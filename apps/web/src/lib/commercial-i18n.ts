export function getCommercialCopy(locale: string) {
  return locale === "ru" ? copy.ru : copy.en;
}
export function commercialError(locale: string, code: unknown) {
  const errors = getCommercialCopy(locale).errors;
  return typeof code === "string" && Object.hasOwn(errors, code)
    ? errors[code as keyof typeof errors]
    : errors.fallback;
}
