export const getUserPlatformCopy = (locale: Locale) => (locale === "ru" ? ru : en);
export function userPlatformError(locale: Locale, code: unknown) {
  const copy = getUserPlatformCopy(locale);
  return typeof code === "string" && Object.hasOwn(en, code) && /^[A-Z_]+$/u.test(code)
    ? copy[code as keyof typeof en]
    : copy.unavailable;
}
